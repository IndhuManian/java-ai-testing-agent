
package AI.Client;

public class MockAIClient {

    public String analyzeFailure(String failureDetails) {

        String lowerFailure = failureDetails.toLowerCase();

        StringBuilder analysis = new StringBuilder();

        analysis.append("AI FAILURE ANALYSIS\n");

        if (lowerFailure.contains("nosuchelementexception")) {

            analysis.append("Failure Category: Element Identification\n");
            analysis.append("Probable Root Cause: Selenium could not locate the element.\n");
            analysis.append("Debugging Steps: Check the XPath or CSS locator, inspect the DOM, and verify whether the element is inside an iframe.\n");
            analysis.append("Suggested Solution: Validate the locator and use an explicit wait if the element loads dynamically.\n");
            analysis.append("Failure Type: Possible Automation Issue\n");
            analysis.append("Rule-based Confidence: High\n");

        } else if (lowerFailure.contains("timeoutexception")) {

            analysis.append("Failure Category: Timeout\n");
            analysis.append("Probable Root Cause: The expected condition was not met within the configured wait time.\n");
            analysis.append("Debugging Steps: Check application response time, element visibility and wait conditions.\n");
            analysis.append("Suggested Solution: Review explicit waits and investigate whether the application response is delayed.\n");
            analysis.append("Failure Type: Application or Automation Issue\n");
            analysis.append("Rule-based Confidence: High\n");

        } else if (lowerFailure.contains("staleelementreferenceexception")) {

            analysis.append("Failure Category: Stale Element\n");
            analysis.append("Probable Root Cause: The DOM changed after Selenium located the element.\n");
            analysis.append("Debugging Steps: Check whether the page refreshed or the element was re-rendered.\n");
            analysis.append("Suggested Solution: Locate the element again after the DOM update.\n");
            analysis.append("Failure Type: Possible Automation Issue\n");
            analysis.append("Rule-based Confidence: High\n");

        } else if (lowerFailure.contains("elementclickinterceptedexception")) {

            analysis.append("Failure Category: Click Interception\n");
            analysis.append("Probable Root Cause: Another element may be covering the target element.\n");
            analysis.append("Debugging Steps: Inspect overlays, pop-ups and element positioning.\n");
            analysis.append("Suggested Solution: Wait until the target is clickable and check for overlays.\n");
            analysis.append("Failure Type: Application or Automation Issue\n");
            analysis.append("Rule-based Confidence: High\n");

        } else if (lowerFailure.contains("elementnotinteractableexception")) {

            analysis.append("Failure Category: Element Interaction\n");
            analysis.append("Probable Root Cause: The element was found but could not be interacted with.\n");
            analysis.append("Debugging Steps: Check visibility, enabled state and whether another element blocks interaction.\n");
            analysis.append("Suggested Solution: Wait for the element to become visible and enabled.\n");
            analysis.append("Failure Type: Possible Automation Issue\n");
            analysis.append("Rule-based Confidence: High\n");

        } else if (lowerFailure.contains("assertionerror")) {

            analysis.append("Failure Category: Assertion Failure\n");
            analysis.append("Probable Root Cause: The actual result did not match the expected result.\n");
            analysis.append("Debugging Steps: Compare expected and actual values and verify the test data.\n");
            analysis.append("Suggested Solution: Check the application behaviour, test data and assertion logic.\n");
            analysis.append("Failure Type: Application, Data or Automation Issue\n");
            analysis.append("Rule-based Confidence: Medium\n");

        } else {

            analysis.append("Failure Category: Unknown\n");
            analysis.append("Probable Root Cause: The failure does not match the currently supported rules.\n");
            analysis.append("Debugging Steps: Review the exception name, error message and stack trace.\n");
            analysis.append("Suggested Solution: Add a specific analysis rule after investigating this failure type.\n");
            analysis.append("Failure Type: Undetermined\n");
            analysis.append("Rule-based Confidence: Low\n");
        }

        analysis.append("\nNote: This is rule-based analysis, not a response generated by an AI model.");

        return analysis.toString();
    }
}
